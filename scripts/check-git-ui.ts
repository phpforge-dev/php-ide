import { _electron as electron, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { mkdir, rm, readFile } from 'node:fs/promises';
import { join } from 'node:path';

const fixture = JSON.parse(execFileSync(process.execPath, ['scripts/create-git-reference.mjs'], { encoding: 'utf8' }));
const command = (...args: string[]) => execFileSync('git', ['-C', fixture.root, ...args], { encoding: 'utf8' });
const app = await electron.launch({ args: ['.'], env: { ...process.env, PHP_IDE_PROJECT: fixture.root } });
try {
  const page = await app.firstWindow(); page.setDefaultTimeout(15_000);
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.getByRole('button', { name: 'Git', exact: true }).click();
  await expect(page.locator('#git-branch')).toContainText('main');
  await expect(page.locator('#git-changes')).toContainText('Preparados para commit (1)');
  await page.locator('[data-path="staged.txt"][data-staged="true"]').click();
  await expect(page.locator('#git-sides')).toHaveText('HEAD   →   Preparado (index)');
  await expect(page.locator('#git-diff')).toContainText('staged version');
  await page.locator('[data-path="staged.txt"][data-staged="false"]').click();
  await expect(page.locator('#git-sides')).toHaveText('Preparado (index)   →   Disco');
  await expect(page.locator('#git-diff')).toContainText('local version');
  await page.locator('[data-path="sample.php"][data-staged="false"]').click();
  await expect(page.locator('#git-diff')).toContainText('Olá');
  await page.getByRole('button', { name: 'Preparar arquivo inteiro', exact: true }).click();
  await expect(page.locator('#git-changes')).toContainText('Preparados para commit (2)');
  await page.locator('#git-message').fill('UI reviewed changes');
  await page.getByRole('button', { name: 'Revisar commit…', exact: true }).click();
  await expect(page.locator('dialog').filter({ hasText: 'Conferir commit local' })).toBeVisible();
  await page.getByRole('button', { name: 'Voltar à revisão', exact: true }).click();
  expect(command('log', '--format=%s', '-1').trim()).toBe('Initial fixture');
  await page.getByRole('button', { name: 'Revisar commit…', exact: true }).click();
  await page.getByRole('button', { name: 'Criar commit local', exact: true }).click();
  await expect(page.locator('dialog').filter({ hasText: 'Conferir commit local' })).toBeHidden();
  await expect(page.locator('#git-feedback')).toContainText('Commit criado:');
  expect(command('show', 'HEAD:staged.txt')).toBe('staged version\n');
  expect(await readFile(join(fixture.root, 'staged.txt'), 'utf8')).toBe('local version\n');
  expect(command('status', '--porcelain')).toContain('?? new.php');
  expect(command('status', '--porcelain')).toContain(' D remove.txt');
  await page.locator('[data-path="staged.txt"][data-staged="false"]').click();
  await expect(page.locator('#git-review')).toBeVisible();
  await expect(page.locator('#git-diff')).toContainText('local version');
  await mkdir('.artifacts', { recursive: true });
  await page.screenshot({ path: '.artifacts/git-review.png' });
  await page.getByRole('button', { name: 'Histórico', exact: true }).click();
  await expect(page.locator('#git-log')).toContainText('UI reviewed changes');
  await page.getByRole('button', { name: 'Projeto', exact: true }).click();
  await expect(page.locator('#git-review')).toBeHidden();
  await expect(page.locator('#tree')).toBeVisible();
  expect(errors).toEqual([]);
  console.log('Git UI: staged/disk diff, stage, cancel, commit, preservation, history and return to editor passed.');
} finally { await app.close(); await rm(fixture.root, { recursive: true, force: true }); }
