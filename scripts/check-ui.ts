import { _electron as electron, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const app=await electron.launch({args:['.']});
try {
 const page=await app.firstWindow();page.setDefaultTimeout(15000);
 console.log('window');
 page.on('console',msg=>{if(msg.type()==='error')console.log(msg.text());});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await expect(page.locator('#project')).toHaveText('php-intelligence');
 await page.locator('#tree').getByRole('button',{name:'probe.php',exact:true}).click();
 await expect(page.locator('#tabs')).toContainText('probe.php');
 await page.getByRole('textbox',{name:'Editor content',exact:true}).focus();
 console.log('editor');
 await page.keyboard.press('Control+g');
 await page.locator('.quick-input-widget input').fill(':8:10');
 await page.locator('.quick-input-widget input').press('Enter');
 await expect(page.locator('.quick-input-widget')).toBeHidden();
 await page.getByRole('textbox',{name:'Editor content',exact:true}).focus();
 await page.keyboard.press('F12');
 await expect(page.locator('#tabs .active')).toContainText('User.php',{timeout:120000});
 await page.getByRole('textbox',{name:'Editor content',exact:true}).focus();
 await page.keyboard.press('Control+g');
 await page.locator('.quick-input-widget input').fill(':9:22');
 await page.locator('.quick-input-widget input').press('Enter');
 await expect(page.locator('.quick-input-widget')).toBeHidden();
 await page.getByRole('button',{name:'Encontrar usos',exact:true}).click();
 await expect(page.locator('.peekview-widget')).toBeVisible({timeout:30000});
 await expect(page.locator('.peekview-widget')).toContainText('probe.php');
 await mkdir('.artifacts',{recursive:true});
 await page.screenshot({path:'.artifacts/references.png'});
 await page.keyboard.press('Escape');
 await page.locator('#tree summary').filter({hasText:'src'}).click();
 await page.locator('#tree').getByRole('button',{name:'Named.php',exact:true}).click();
 await page.getByRole('textbox',{name:'Editor content',exact:true}).focus();
 await page.keyboard.press('Control+g');
 await page.locator('.quick-input-widget input').fill(':7:22');
 await page.locator('.quick-input-widget input').press('Enter');
 await expect(page.locator('.quick-input-widget')).toBeHidden();
 await page.getByRole('button',{name:'Implementações',exact:true}).click();
 await expect(page.locator('.peekview-widget')).toBeVisible({timeout:30000});
 await expect(page.locator('.peekview-widget')).toContainText('User.php');
 await expect(page.locator('.peekview-widget')).toContainText('Admin.php');
 await page.screenshot({path:'.artifacts/implementations.png'});
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Bancos',exact:true}).click();
 await expect(page.locator('#db')).toBeVisible();
 await page.getByRole('button',{name:'Agente',exact:true}).click();
 await mkdir('.artifacts',{recursive:true});
 await page.screenshot({path:'.artifacts/ide.png'});
 console.log(JSON.stringify({navigation:'probe.php → User.php; Encontrar usos → probe.php; Implementações → User.php e Admin.php',rendererErrors:errors}));
 expect(errors).toEqual([]);
}catch(error){console.error(error);throw error;}finally{await app.close();}
